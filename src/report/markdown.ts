import { redactSecrets } from "../redact.js";
import { scoreEquation } from "../score.js";
import type { Report } from "../types.js";

export function formatMarkdown(report: Report): string {
  const lines: string[] = [
    `# clawscore report`,
    "",
    `**Score:** ${report.score} / 100  `,
    `**Score math:** ${scoreEquation(report.findings)} (repeat ids count once)  `,
    `**Grade:** ${report.grade}  `,
    `**Path:** \`${report.path}\`  `,
    `**OpenClaw version:** ${report.openclawVersion ?? "unknown"}  `,
    `**clawscore:** ${report.toolVersion}`,
    "",
    "## Summary",
    "",
    `| Severity | Count |`,
    `| --- | ---: |`,
    `| critical | ${report.summary.critical} |`,
    `| high | ${report.summary.high} |`,
    `| medium | ${report.summary.medium} |`,
    `| low | ${report.summary.low} |`,
    `| info | ${report.summary.info} |`,
    "",
  ];
  if (report.findings.length === 0) {
    lines.push("No findings.");
  } else {
    lines.push("## Findings", "");
    for (const f of report.findings) {
      lines.push(`### \`${f.id}\` (${f.severity}, −${f.weight} pts)`);
      lines.push("");
      if (f.title) lines.push(`**${f.title}**`);
      lines.push("");
      lines.push(`- **Evidence:** ${f.evidence}`);
      lines.push(`- **Fix:** ${f.fix}`);
      if (f.file) lines.push(`- **File:** \`${f.file}\``);
      lines.push("");
    }
  }
  lines.push("---");
  lines.push("Generated by [clawscore](https://github.com/realmpastai-web/clawscore). Not affiliated with OpenClaw.");
  lines.push("");
  return redactSecrets(lines.join("\n"));
}
